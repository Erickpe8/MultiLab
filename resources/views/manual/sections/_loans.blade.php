<div class="space-y-6">
    <div>
        <p class="text-xs uppercase tracking-[0.4em] text-[var(--text-muted)]">Sección 8 · Préstamos de materiales</p>
        <h2 class="text-2xl font-semibold text-[var(--text)]">Solicitud, aprobación y devolución</h2>
    </div>
    <article class="rounded-3xl border border-[var(--border)] bg-[var(--card)] p-5 shadow-sm text-sm text-[var(--text-muted)]">
        <p class="text-xs uppercase tracking-[0.3em] text-[var(--text-muted)]">8.1 Solicitar préstamo</p>
        <ol class="mt-3 space-y-2 list-decimal pl-5">
            <li>Elige el material, ajusta la cantidad requerida y describe el uso académico.</li>
            <li>Elige fechas de inicio y devolución, y agrega notas adicionales si vas a trabajar con grupos.</li>
            <li>Envía la solicitud; el estado aparecerá como "Pendiente" hasta que un Administrador Auxiliar la revise.</li>
        </ol>
        <div class="mt-3 text-xs text-blue-500">Nota: los estudiantes solo ven sus propios préstamos; los docentes pueden solicitar y recibir confirmación.</div>
    </article>
    <article class="rounded-3xl border border-[var(--border)] bg-[var(--card)] p-5 shadow-sm text-sm text-[var(--text-muted)]">
        <p class="text-xs uppercase tracking-[0.3em] text-[var(--text-muted)]">8.2 Aprobación de préstamos (Administrador Auxiliar)</p>
        <ol class="mt-3 space-y-2 list-decimal pl-5">
            <li>Verifica que el material solicitado esté marcado como "Disponible" y que exista stock suficiente.</li>
            <li>Revisa si el usuario tiene préstamos vencidos o pendientes antes de aprobar nuevos ítems.</li>
            <li>Confirma la aprobación; el crédito quedará con estado "Activo" hasta que se registre la devolución.</li>
        </ol>
        <div class="mt-3 rounded-2xl border border-dashed border-[var(--border)] p-3 text-xs text-[var(--text-muted)]">
            <p class="font-semibold text-[var(--text)]">Recomendación</p>
            <p>Documenta observaciones si el equipo prestado está en condiciones especiales o si se aplica una prórroga.</p>
        </div>
    </article>
    <article class="rounded-3xl border border-[var(--border)] bg-[var(--card)] p-5 shadow-sm text-sm text-[var(--text-muted)]">
        <p class="text-xs uppercase tracking-[0.3em] text-[var(--text-muted)]">8.3 Devolución de materiales</p>
        <ol class="mt-3 space-y-2 list-decimal pl-5">
            <li>El Administrador Auxiliar recibe el material, verifica la condición física y actualiza la fecha de devolución.</li>
            <li>Marca el préstamo como "Devuelto" y actualiza el stock disponible en el inventario.</li>
            <li>Si el material llega dañado, genera una nota en auditoría y notifica al Super Administrador para seguimiento.</li>
        </ol>
        <div class="mt-3 text-xs text-amber-500">Error común: olvidar cerrar el préstamo. Siempre verifica que el estado cambie de "Activo" a "Devuelto".</div>
    </article>
</div>
